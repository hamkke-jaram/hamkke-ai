import { describe, expect, it } from 'vitest';
import { audioTrackPresence } from './audioTrack';

function concat(...chunks: Uint8Array[]): Uint8Array<ArrayBuffer> {
  const result = new Uint8Array(chunks.reduce((size, chunk) => size + chunk.length, 0));
  let offset = 0;
  for (const chunk of chunks) {
    result.set(chunk, offset);
    offset += chunk.length;
  }
  return result;
}

const ascii = (value: string) => new TextEncoder().encode(value);

function box(type: string, ...chunks: Uint8Array[]) {
  const size = new Uint8Array(4);
  new DataView(size.buffer).setUint32(0, 8 + chunks.reduce((sum, chunk) => sum + chunk.length, 0));
  return concat(size, ascii(type), ...chunks);
}

function mp4Track(handler: string) {
  return box('trak', box('mdia', box('hdlr', new Uint8Array(8), ascii(handler))));
}

function ebml(type: number[], payload: Uint8Array) {
  // All fixture elements have a payload length under 127 and fit a single size octet.
  return concat(Uint8Array.of(...type, 0x80 | payload.length), payload);
}

function webm(...types: number[]) {
  const tracks = ebml([0x16, 0x54, 0xae, 0x6b], concat(...types.map(type => ebml([0xae], ebml([0x83], Uint8Array.of(type))))));
  const header = ebml([0x1a, 0x45, 0xdf, 0xa3], new Uint8Array());
  // An open-ended Segment is typical for files generated by MediaRecorder.
  return concat(header, Uint8Array.of(0x18, 0x53, 0x80, 0x67, 0xff), tracks);
}

describe('audioTrackPresence', () => {
  it('checks MP4 or MOV metadata after the media payload', async () => {
    const bytes = concat(box('ftyp', ascii('qt  ')), box('mdat', new Uint8Array(400)), box('moov', mp4Track('vide')));
    expect(await audioTrackPresence(new Blob([bytes]))).toBe('absent');
  });

  it('recognizes an audio handler regardless of audio codec or loudness', async () => {
    const bytes = box('moov', mp4Track('vide'), mp4Track('tmcd'), mp4Track('soun'));
    expect(await audioTrackPresence(new Blob([bytes]))).toBe('present');
  });

  it('distinguishes video-only WebM from WebM with an audio track', async () => {
    expect(await audioTrackPresence(new Blob([webm(1)]))).toBe('absent');
    expect(await audioTrackPresence(new Blob([webm(1, 2)]))).toBe('present');
  });

  it('keeps unrecognized and truncated track metadata unknown', async () => {
    const bytes = box('moov', mp4Track('vide'), mp4Track('soun'));
    expect(await audioTrackPresence(new Blob([bytes.slice(0, -2)]))).toBe('unknown');
    expect(await audioTrackPresence(new Blob([box('moov', mp4Track('vide'), box('trak'))]))).toBe('unknown');
    expect(await audioTrackPresence(new Blob([webm(1, 2).slice(0, -1)]))).toBe('unknown');
    expect(await audioTrackPresence(new Blob([ascii('not a known video')]))).toBe('unknown');
  });

  it('does not inspect a stopped file', async () => {
    await expect(audioTrackPresence(new Blob([webm(1)]), AbortSignal.abort())).rejects.toMatchObject({ name: 'AbortError' });
  });
});
