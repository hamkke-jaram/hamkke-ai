/**
 * 눈에 보이지 않는 글자. 낱말 사이에 끼워 넣으면 검사를 비켜 갈 수 있어 검사 전에 지운다(공백으로 바꾸지 않는다).
 * - \p{Cf}: 폭 없는 공백·이음표(U+200B~U+200D), 낱말 이음표(U+2060), BOM(U+FEFF), 부드러운 붙임표(U+00AD), 방향 표시 등
 * - U+034F(결합 자소 이음표), U+115F·U+1160(한글 채움 문자. U+3164·U+FFA0 도 NFKC 를 거치면 U+1160 이 된다),
 *   U+17B4·U+17B5, U+FE00~U+FE0F(이형 선택자)
 */
export const INVISIBLE_CHARACTERS = /[\p{Cf}\u034F\u115F\u1160\u17B4\u17B5\uFE00-\uFE0F]/gu;

/**
 * 검사하기 전에 글자를 고르게 맞춘다. 순서가 중요하다.
 * 1) NFKC: 전각 숫자·영문('３살' → '3살'), 풀어 쓴 한글 자모(NFD) → 완성형, 한글 채움 문자 → U+1160
 * 2) 보이지 않는 글자를 지운다(1에서 U+1160 으로 모인 채움 문자 포함)
 * 여러 번 거쳐도 결과가 같다.
 */
export function normaliseForCheck(text: string): string {
  return text.normalize('NFKC').replace(INVISIBLE_CHARACTERS, '');
}

