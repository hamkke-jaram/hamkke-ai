/**
 * '-ㄴ/는/ㄹ 듯'(화가 난 듯, 우는 듯, 울 듯): '듯' 앞 글자의 받침이 ㄴ 이나 ㄹ 이면 짐작하는 말이다.
 * '살펴보듯', '쏟아지듯'(빗대는 말)은 받침이 없어 지나간다.
 */
function hasGuessNoun(text: string): boolean {
  for (const match of text.matchAll(/([가-힣])\s*듯/g)) {
    const finalConsonant = (match[1]!.charCodeAt(0) - 0xac00) % 28;
    if (finalConsonant === 4 || finalConsonant === 8) return true; // 받침 ㄴ, ㄹ
  }
  return false;
}

